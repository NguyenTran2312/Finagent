"""Read-only lint of config/ticker_templates.yaml against form codes in the corpus.

Run from the repository root:

    python -I -X utf8 scripts/lint_ticker_templates.py [--db PATH] [--draft]

Form codes are looked up per document in the folded first-page text and the folded
table contexts: tctd -> bank, ctck -> securities, dnbh -> insurance, B0x-DN -> corporate
(fold_text("B02-DN") == "b02 dn"). A ticker is classified over all of its documents.

--draft prints a YAML draft (sorted by ticker) for hand review. Without it, one line is
printed per mismatch (config differs from detected, or ticker missing from config) or
unclassified ticker, and the exit code is 1 if there is any. A config line carrying a
`# reviewed: <reason>` comment is the hand-review verdict: its contradictions print as
`NOTE (reviewed): ...` and do not affect the exit code.

The database is opened read-only (mode=ro) and is never written.
"""

from __future__ import annotations

import argparse
import re
import sqlite3
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.extraction.templates import (  # noqa: E402
    DEFAULT_TICKER_TEMPLATES,
    TemplateConfigError,
    load_ticker_templates,
)
from src.preprocess.cleaner import fold_text  # noqa: E402

DEFAULT_DB = REPO_ROOT / "data" / "databases" / "corpus.sqlite3"

# Folded-text markers, checked in this order; a document may match several.
MARKERS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("bank", re.compile(r"\btctd\b")),
    ("securities", re.compile(r"\bctck\b")),
    ("insurance", re.compile(r"\bdnbh\b")),
    ("corporate", re.compile(r"\bb ?0[1-9] ?dn\b")),
)


def connect(db: Path) -> sqlite3.Connection:
    return sqlite3.connect(f"file:{db.as_posix()}?mode=ro", uri=True)


def detect_document(cur: sqlite3.Cursor, doc_id: str) -> set[str]:
    parts = [r[0] or "" for r in cur.execute(
        "SELECT text FROM pages WHERE doc_id = ? AND page_index = 0", (doc_id,))]
    parts += [r[0] for r in cur.execute(
        "SELECT context FROM tables WHERE doc_id = ? AND context IS NOT NULL", (doc_id,))]
    folded = fold_text("\n".join(parts))
    return {name for name, pattern in MARKERS if pattern.search(folded)}


def classify(db: Path) -> dict[str, tuple[Counter, Counter]]:
    """ticker -> (documents per template, documents total as Counter{'docs': n})."""
    out: dict[str, tuple[Counter, Counter]] = {}
    con = connect(db)
    try:
        cur = con.cursor()
        docs = cur.execute("SELECT ticker, doc_id FROM documents ORDER BY ticker, doc_id").fetchall()
        for ticker, doc_id in docs:
            seen, total = out.setdefault(ticker.strip().upper(), (Counter(), Counter()))
            total["docs"] += 1
            seen.update(detect_document(cur, doc_id))
    finally:
        con.close()
    return out


def verdict(seen: Counter) -> tuple[str | None, bool]:
    """(majority template or None, multi-form)."""
    if not seen:
        return None, False
    ranked = sorted(seen.items(), key=lambda kv: (-kv[1], kv[0]))
    return ranked[0][0], len(seen) > 1


def codes_text(seen: Counter, total: Counter) -> str:
    if not seen:
        return "none"
    return ", ".join(f"{k} {v}/{total['docs']}" for k, v in sorted(seen.items()))


def draft(result: dict[str, tuple[Counter, Counter]]) -> str:
    lines = ["# Ticker -> statement template. Draft generated by scripts/lint_ticker_templates.py;",
             "# hand-reviewed config (see spec section 2, decision 4)."]
    for ticker in sorted(result):
        seen, total = result[ticker]
        template, multi = verdict(seen)
        codes = codes_text(seen, total)
        if template is None:
            lines.append(f"# {ticker}: unclassified  # form codes seen: none")
        elif multi:
            lines.append(f"{ticker}: {template}  # MULTI-FORM: form codes seen: {codes}")
        else:
            lines.append(f"{ticker}: {template}  # form codes seen: {codes}")
    return "\n".join(lines) + "\n"


_REVIEWED = re.compile(r"^\s*([^#\s:][^:]*?)\s*:[^#]*#.*#\s*reviewed:\s*\S", re.IGNORECASE)


def reviewed_tickers(config_path: Path) -> set[str]:
    """Tickers whose config line carries a `# reviewed: <reason>` comment (YAML drops comments)."""
    out = set()
    for line in config_path.read_text(encoding="utf-8").splitlines():
        m = _REVIEWED.match(line)
        if m:
            out.add(m.group(1).strip().upper())
    return out


def lint(result: dict[str, tuple[Counter, Counter]], config_path: Path) -> tuple[list[str], list[str]]:
    """(problems, notes). A reviewed ticker's contradiction is a note, not a problem."""
    templates = load_ticker_templates(config_path)
    reviewed = reviewed_tickers(config_path)
    problems, notes = [], []
    for ticker in sorted(result):
        seen, total = result[ticker]
        detected, _ = verdict(seen)
        configured = templates.get(ticker)
        codes = codes_text(seen, total)
        if configured is None:
            detail = (f"unclassified (form codes seen: none)" if detected is None
                      else f"missing from config (detected {detected}; form codes seen: {codes})")
            problems.append(f"{ticker}: {detail}")
        elif detected is None:
            msg = f"{ticker}: unclassified (configured: {configured}; form codes seen: none)"
            (notes if ticker in reviewed else problems).append(msg)
        elif configured != detected:
            msg = f"{ticker}: config {configured} != detected {detected} (form codes seen: {codes})"
            (notes if ticker in reviewed else problems).append(msg)
    return problems, notes


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--config", type=Path, default=DEFAULT_TICKER_TEMPLATES)
    parser.add_argument("--draft", action="store_true", help="print a YAML draft instead of linting")
    args = parser.parse_args(argv)
    if not args.db.is_file():
        parser.error(f"database not found: {args.db} (pass --db explicitly when the corpus "
                     "is not under this checkout's data/databases/)")
    result = classify(args.db)
    if args.draft:
        sys.stdout.write(draft(result))
        return 0
    try:
        problems, notes = lint(result, args.config)
    except TemplateConfigError as exc:
        print(f"config error: {exc}")
        return 1
    for line in notes:
        print(f"NOTE (reviewed): {line}")
    for line in problems:
        print(line)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
